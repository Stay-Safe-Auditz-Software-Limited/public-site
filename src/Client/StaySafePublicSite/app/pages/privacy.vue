        cookies which will expire when you close your browsing session.&nbsp; These cookies do not
        collect information that could be used for marketing purposes.
      </p>
      <h3>
        <strong><em>Functionality cookies</em></strong>
      </h3>
      <p>
        These cookies allow a website to remember choices you make and provide enhanced, more
