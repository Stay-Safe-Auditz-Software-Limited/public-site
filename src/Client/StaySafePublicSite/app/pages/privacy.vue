      <h2>WHAT ARE COOKIES</h2>
      <p>
        Cookies are text files containing small amounts of information which are downloaded to your
        browsing device, e.g. a computer or smartphone, when you visit a website.&nbsp; Cookies can
        be recognised by the website that downloaded them, or by other websites that use the same
        cookies.&nbsp; This helps a website know if the browsing device has visited that or other
        websites before.&nbsp;
      </p>
      <p>
        Cookies can be used to collect information relating to your use of a website or your device,
        let you navigate between pages effectively, help to remember your preferences and generally
        improve your browsing experience.&nbsp; Cookies can also help ensure advertising you see
        online is more relevant to you and your interests.
      </p>
      <p>
        Cookies can be
        <em>session</em>
        or
        <em>persistent</em>
        cookies.&nbsp;
        <em>Session</em>
        cookies are temporary and only stay on your browser until you stop browsing.&nbsp;
        <em>Persistent</em>
        cookies stay on your device until they expire or are deleted.
      </p>
      <p>
        The cookies used on our website may be first party cookies (i.e. set by us) or third party
        cookies (i.e. cookies set on our website by a person other than us).&nbsp; The third party
        companies that place cookies on our website will have their own privacy policies.
      </p>
